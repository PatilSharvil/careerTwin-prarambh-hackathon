import React, { useState } from 'react';
import { Card } from '../ui/Card';
import { Button } from '../ui/Button';
import {
  Terminal,
  Copy,
  Check,
  AlertCircle,
  HelpCircle,
  PlayCircle,
} from 'lucide-react';

export interface EvalNotRunStateProps {
  onRetry?: () => void;
  isLoading?: boolean;
}

export const EvalNotRunState: React.FC<EvalNotRunStateProps> = ({
  onRetry,
  isLoading = false,
}) => {
  const [copied, setCopied] = useState<boolean>(false);
  const command = 'make eval';

  const handleCopy = () => {
    navigator.clipboard.writeText(command);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="max-w-3xl mx-auto py-8">
      <Card className="p-8 border-slate-300 bg-white shadow-sm text-center">
        <div className="w-14 h-14 rounded-2xl bg-amber-50 text-amber-600 border border-amber-200 flex items-center justify-center mx-auto mb-4">
          <AlertCircle className="w-7 h-7" />
        </div>

        <h2 className="text-xl font-bold text-slate-900 mb-2">
          Evaluation Report Not Found
        </h2>

        <p className="text-sm text-slate-600 max-w-lg mx-auto mb-6 leading-relaxed">
          The test evaluation suite has not been executed yet. In accordance with the system specification, the evaluation report is generated by running the automated eval runner in your terminal.
        </p>

        {/* Terminal Box */}
        <div className="max-w-md mx-auto mb-6 text-left">
          <div className="text-xs font-semibold text-slate-500 uppercase tracking-wider mb-1.5 flex items-center gap-1">
            <Terminal className="w-3.5 h-3.5 text-slate-400" />
            <span>Terminal Command</span>
          </div>

          <div className="flex items-center justify-between p-3.5 rounded-xl bg-slate-900 text-slate-100 font-mono text-sm shadow-inner">
            <div className="flex items-center gap-2">
              <span className="text-emerald-400 font-bold">$</span>
              <span>{command}</span>
            </div>

            <button
              onClick={handleCopy}
              className="p-1.5 rounded-lg text-slate-400 hover:text-white hover:bg-slate-800 transition-colors"
              title="Copy to clipboard"
              aria-label="Copy command"
            >
              {copied ? (
                <Check className="w-4 h-4 text-emerald-400" />
              ) : (
                <Copy className="w-4 h-4" />
              )}
            </button>
          </div>
        </div>

        {/* Explanation points */}
        <div className="max-w-md mx-auto text-left text-xs text-slate-500 space-y-2 mb-6 p-4 rounded-xl bg-slate-50 border border-slate-100">
          <div className="font-semibold text-slate-700 flex items-center gap-1.5">
            <HelpCircle className="w-3.5 h-3.5 text-primary-600" />
            <span>What happens when you run this?</span>
          </div>
          <p>
            1. Executes tests for all 14 metrics across the 6 judging categories.
          </p>
          <p>
            2. Benchmarks skill gaps against all 6 hand-labeled golden personas.
          </p>
          <p>
            3. Executes ADK agent trajectory tests and outputs <code className="font-mono text-slate-700 bg-slate-200/80 px-1 py-0.5 rounded">backend/eval/report.json</code>.
          </p>
        </div>

        {onRetry && (
          <div className="pt-2">
            <Button
              variant="primary"
              size="md"
              onClick={onRetry}
              disabled={isLoading}
              isLoading={isLoading}
            >
              <PlayCircle className="w-4 h-4 mr-1.5" />
              Check for Generated Report
            </Button>
          </div>
        )}
      </Card>
    </div>
  );
};
