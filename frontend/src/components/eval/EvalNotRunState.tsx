import React, { useState } from 'react';
import { Card } from '../ui/Card';
import { Button } from '../ui/Button';
import {
  Terminal,
  Copy,
  Check,
  AlertCircle,
  HelpCircle,
  PlayCircle,
} from 'lucide-react';

export interface EvalNotRunStateProps {
  onRetry?: () => void;
  isLoading?: boolean;
}

export const EvalNotRunState: React.FC<EvalNotRunStateProps> = ({
  onRetry,
  isLoading = false,
}) => {
  const [copied, setCopied] = useState<boolean>(false);
  const command = 'make eval';

  const handleCopy = () => {
    navigator.clipboard.writeText(command);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="max-w-3xl mx-auto py-8">
      <Card className="p-8 border-2 border-black bg-[#fdfbf7] rounded-3xl shadow-neo text-center">
        <div className="w-16 h-16 rounded-2xl bg-[#ffe566] text-black border-2 border-black shadow-neo flex items-center justify-center mx-auto mb-4">
          <AlertCircle className="w-8 h-8" />
        </div>

        <h2 className="text-2xl font-black text-black mb-2">
          Evaluation Report Not Found
        </h2>

        <p className="text-sm font-bold text-neutral-600 max-w-lg mx-auto mb-6 leading-relaxed">
          The test evaluation suite has not been executed yet. In accordance with the system specification, the evaluation report is generated by running the automated eval runner in your terminal.
        </p>

        {/* Terminal Box */}
        <div className="max-w-md mx-auto mb-6 text-left">
          <div className="text-xs font-black text-black uppercase tracking-wider mb-2 flex items-center gap-1.5">
            <Terminal className="w-4 h-4 text-black" />
            <span>Terminal Command</span>
          </div>

          <div className="flex items-center justify-between p-4 rounded-2xl bg-black text-[#79e7a8] font-mono text-sm border-2 border-black shadow-neo-sm">
            <div className="flex items-center gap-2 font-bold">
              <span className="text-[#ffe566] font-black">$</span>
              <span>{command}</span>
            </div>

            <button
              onClick={handleCopy}
              className="p-2 rounded-xl text-black bg-[#ffe566] hover:bg-[#ffd633] border-2 border-black shadow-neo-xs active:translate-x-0.5 active:translate-y-0.5 transition-all"
              title="Copy to clipboard"
              aria-label="Copy command"
            >
              {copied ? (
                <Check className="w-4 h-4 text-black" />
              ) : (
                <Copy className="w-4 h-4 text-black" />
              )}
            </button>
          </div>
        </div>

        {/* Explanation points */}
        <div className="max-w-md mx-auto text-left text-xs text-neutral-700 font-bold space-y-2 mb-6 p-4 rounded-2xl bg-white border-2 border-black shadow-neo-xs">
          <div className="font-black text-black flex items-center gap-1.5 text-xs mb-1">
            <HelpCircle className="w-4 h-4 text-black" />
            <span>What happens when you run this?</span>
          </div>
          <p>
            1. Executes tests for all 14 metrics across the 6 judging categories.
          </p>
          <p>
            2. Benchmarks skill gaps against all 6 hand-labeled golden personas.
          </p>
          <p>
            3. Executes ADK agent trajectory tests and outputs <code className="font-mono text-black bg-[#ffe566] px-1.5 py-0.5 rounded border border-black font-bold">backend/eval/report.json</code>.
          </p>
        </div>

        {onRetry && (
          <div className="pt-2">
            <Button
              variant="primary"
              size="lg"
              onClick={onRetry}
              disabled={isLoading}
              isLoading={isLoading}
            >
              <PlayCircle className="w-5 h-5 mr-2 text-black" />
              Check for Generated Report
            </Button>
          </div>
        )}
      </Card>
    </div>
  );
};
